#!/usr/bin/env node
/**
 * Seeds / refreshes `public.template_catalog` from src/lib/templates.ts.
 *
 *   node scripts/seed-templates.mjs            → writes supabase/seed/template_catalog.sql
 *   node scripts/seed-templates.mjs --push     → also upserts into Supabase
 *                                                (needs SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY env)
 *
 * The service-role key bypasses RLS — keep it out of the browser and out of git.
 */
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tmp = join(root, 'tests', '.tmp');
mkdirSync(tmp, { recursive: true });
const out = join(tmp, 'templates.bundle.mjs');

await build({
  entryPoints: [join(root, 'src/lib/templates.ts')],
  bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'silent',
});
const { TEMPLATES, LAYOUT_META } = await import(pathToFileURL(out).href);

const rows = TEMPLATES.map((t, i) => ({
  id: t.id,
  name: t.name,
  layout: t.layout,
  family_label: LAYOUT_META[t.layout].label,
  tagline: t.tagline,
  best_for: t.bestFor,
  strengths: t.strengths,
  palette: t.pal,
  mods: t.mods,
  sort_order: i,
  is_active: true,
}));

// ---- SQL file (idempotent upsert) ----
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const sql = [
  '-- generated by scripts/seed-templates.mjs — do not edit by hand',
  'insert into public.template_catalog (id, name, layout, family_label, tagline, best_for, strengths, palette, mods, sort_order, is_active) values',
  rows.map((r) => `  (${q(r.id)}, ${q(r.name)}, ${q(r.layout)}, ${q(r.family_label)}, ${q(r.tagline)}, ${arr(r.best_for)}, ${arr(r.strengths)}, ${q(JSON.stringify(r.palette))}::jsonb, ${arr(r.mods)}, ${r.sort_order}, true)`).join(',\n'),
  'on conflict (id) do update set',
  '  name = excluded.name, layout = excluded.layout, family_label = excluded.family_label, tagline = excluded.tagline,',
  '  best_for = excluded.best_for, strengths = excluded.strengths, palette = excluded.palette, mods = excluded.mods,',
  '  sort_order = excluded.sort_order, is_active = true;',
  '',
].join('\n');
mkdirSync(join(root, 'supabase/seed'), { recursive: true });
writeFileSync(join(root, 'supabase/seed/template_catalog.sql'), sql);
console.log(`✓ wrote supabase/seed/template_catalog.sql (${rows.length} templates)`);

// ---- keep the all-in-one setup script in sync ----
// SETUP_ALL_IN_ONE.sql ends with an inlined copy of this seed so a fresh project
// can be set up with one paste. It went stale before, so it is now rewritten
// here on every run instead of by hand.
const marker = '-- ======================= template catalog seed =======================';
const allInOne = join(root, 'supabase', 'SETUP_ALL_IN_ONE.sql');
if (existsSync(allInOne)) {
  const before = readFileSync(allInOne, 'utf8');
  const cut = before.indexOf(marker);
  if (cut === -1) {
    console.warn(`⚠ ${marker} not found in supabase/SETUP_ALL_IN_ONE.sql — left untouched`);
  } else {
    const head = before.slice(0, cut + marker.length);
    writeFileSync(allInOne, `${head}\n${sql.replace(/^-- generated by[^\n]*\n/, '-- generated by scripts/seed-templates.mjs — do not edit by hand\n')}`);
    console.log(`✓ refreshed the catalog block in supabase/SETUP_ALL_IN_ONE.sql (${rows.length} templates)`);
  }
}

// ---- optional direct push ----
if (process.argv.includes('--push')) {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) { console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY to push.'); process.exit(1); }
  const { createClient } = await import('@supabase/supabase-js');
  const sb = createClient(url, key, { auth: { persistSession: false } });
  const { error } = await sb.from('template_catalog').upsert(rows, { onConflict: 'id' });
  if (error) { console.error('✗ push failed:', error.message); process.exit(1); }
  console.log(`✓ upserted ${rows.length} templates into template_catalog`);
}
