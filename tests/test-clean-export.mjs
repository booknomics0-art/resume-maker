/**
 * Clean export test — the user-visible promise:
 *
 *   "Every PDF you download is exactly your resume — no watermark, no CraftCV
 *    credit line, no app link, no placeholder boxes."
 *
 * A resume-maker watermark is the single most common reason users leave a
 * product, so this test makes the promise machine-verifiable:
 *
 *   1. It renders EVERY template in the catalogue (50 designs) through the
 *      app's real rendering path (Preview.tsx via react-dom/server) with
 *      resumes that have no photo, and asserts the sheet markup contains no
 *      app branding, no <a>/href, and that every photo placeholder is tagged
 *      with the `ph` class the print stylesheet hides.
 *   2. It statically verifies the print pipeline in styles.css: only
 *      .print-root is visible, the sheet is exact A4 at zero margins, and
 *      .ph placeholders never reach the page.
 *   3. It verifies Editor.tsx keeps the print root clean — the only thing
 *      inside it is <Preview r={r} />, nothing from the app chrome.
 *
 *   node tests/test-clean-export.mjs
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { checks, root, tmpDir } from './_harness.mjs';

mkdirSync(tmpDir, { recursive: true });

// ---- bundle the catalogue + renderer + the flagship sample -----------------
const entry = join(tmpDir, 'clean-ssr-entry.tsx');
const outfile = join(tmpDir, 'clean-ssr.js');
writeFileSync(entry, `
  import { renderToStaticMarkup } from 'react-dom/server';
  import Preview from '../../src/components/Preview';
  import * as lib from '../../src/lib/templates';
  import { sampleResume } from '../../src/lib/store';
  export { lib };
  export const render = (resume: any, tpl: any) =>
    renderToStaticMarkup(<Preview r={resume} tpl={tpl} />);
  export const sample = () => sampleResume();
`);

await build({
  entryPoints: [entry],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  jsx: 'automatic',
  outfile,
  logLevel: 'error',
  external: ['react', 'react-dom', '@supabase/supabase-js'],
  // the app reads Vite env vars; in Node they are simply absent
  define: {
    'import.meta.env.VITE_SUPABASE_URL': 'undefined',
    'import.meta.env.VITE_SUPABASE_ANON_KEY': 'undefined',
  },
});

const { lib, render, sample } = await import(pathToFileURL(outfile).href);
const { TEMPLATES } = lib;

// The shipped flagship sample (Amit Shukla) must be clean too.
const sampleR = sample();

// A second fixture with no photo, so every placeholder path is exercised.
const noPhoto = {
  id: 'clean-test', name: 'Clean test', fieldId: 'it', templateId: '',
  createdAt: 0, updatedAt: 0, step: 6, fresher: false,
  personal: {
    fullName: 'Ananya Iyer', headline: 'Senior Marketing Manager',
    email: 'ananya.iyer@example.com', phone: '+91 98450 22117', city: 'Bengaluru',
    linkedin: 'linkedin.com/in/ananyaiyer', website: 'ananya.marketing', photo: '',
  },
  summary: 'Marketing manager with nine years across D2C and B2B SaaS. Built demand engines that took two products to ₹40 Cr ARR.',
  bestExperience: 'Rebuilt the onboarding funnel in one quarter — activation 31% → 47%.',
  experience: [
    { id: 'e1', role: 'Senior Marketing Manager', company: 'Kite Software', location: 'Bengaluru',
      start: 'Jul 2021', end: '', current: true,
      bullets: ['Pipeline up 62% YoY on a flat budget'] },
  ],
  education: [{ id: 'd1', degree: 'MBA, Marketing', school: 'Symbiosis', location: 'Pune', year: '2017', note: 'Gold medal' }],
  skills: ['SEO', 'Google Ads', 'SQL', 'Brand Strategy'],
  projects: [{ id: 'p1', name: 'Lifecycle Rebuild', link: 'case study', points: 'Cut email churn 24%' }],
  certs: [{ id: 'c1', name: 'GA4 Certification', issuer: 'Google', year: '2023' }],
  languages: [{ id: 'l1', name: 'English', level: 'Professional' }],
  achievements: ['Marketer of the Year 2024'],
  hobbies: ['Trekking'],
};

// Strings that would mean app branding leaked onto the candidate's document.
// (User content like linkedin.com/in/… is fine — that is THEIR data.)
const BRAND = [
  'craftcv', 'craft cv', 'resume studio', 'netlify', 'supabase',
  'powered by', 'generated by', 'free resume', 'resume builder', 'template-preview',
  'support@', 'hello@', 'privacy@', 'legal@', '© 20', 'crafted with',
];

const out = [];
const ok = (name, cond) => out.push([name, !!cond]);

let brandHits = [];
let linkHits = [];
let untaggedPlaceholder = [];

const scan = (html, label) => {
  const lower = html.toLowerCase();
  for (const b of BRAND) {
    if (lower.includes(b)) brandHits.push(`${label}: "${b}"`);
  }
  if (/<a[\s>]/.test(html) || /href\s*=/.test(html)) linkHits.push(label);
  // any <div> photo placeholder must carry the .ph class, or the print CSS
  // cannot hide it (real <img> photos never need tagging)
  for (const m of html.matchAll(/<div class="([^"]*)"/g)) {
    const cls = m[1];
    if (!/avatar|seal|spine-mono|s-photo|band-photo|tint-photo|rail-photo|mast-photo/.test(cls)) continue;
    if (!cls.includes('ph')) untaggedPlaceholder.push(`${label}: <div class="${cls}">`);
  }
};

for (const t of TEMPLATES) {
  scan(render({ ...noPhoto, templateId: t.id }, t), `tpl:${t.id}`);
}
// the shipped sample in its default design
scan(render(sampleR, lib.templateById(sampleR.templateId)), 'sample');

ok(`every template renders (catalogue ${TEMPLATES.length})`, TEMPLATES.length >= 50);
ok('no app branding string in any rendered sheet', brandHits.length === 0);
ok('no <a> tag or href in any rendered sheet (links never reach the PDF)', linkHits.length === 0);
ok('every photo placeholder is tagged .ph so print hides it', untaggedPlaceholder.length === 0);
if (brandHits.length) console.log('   branding hits:', brandHits.slice(0, 8).join(' | '));
if (linkHits.length) console.log('   link hits:', linkHits.slice(0, 8).join(' | '));
if (untaggedPlaceholder.length) console.log('   untagged:', untaggedPlaceholder.slice(0, 8).join(' | '));

// ---- the print pipeline must be leak-proof ---------------------------------
const styles = readFileSync(join(root, 'src', 'styles.css'), 'utf8');
const templatesCss = readFileSync(join(root, 'src', 'templates.css'), 'utf8');
const previewSrc = readFileSync(join(root, 'src', 'components', 'Preview.tsx'), 'utf8');
const printBlock = styles.slice(styles.indexOf('@media print'));

ok('print: A4 pages, zero margins (@page)',
  /@page\s*\{\s*size:\s*A4;\s*margin:\s*0;?\s*\}/.test(styles));
ok('print: only .print-root is shown',
  /@media print[\s\S]*\.print-root\s*{\s*display:\s*block/.test(printBlock));
ok('print: all app chrome is hidden (body * visibility)',
  /body \* \{\s*visibility:\s*hidden/.test(printBlock));
ok('print: the sheet is exact A4 width (210mm)',
  /\.print-root \.sheet \{[^}]*width:\s*210mm/.test(printBlock));
ok('print: .ph photo placeholders never reach the page',
  /\.print-root \.sheet \.ph \{\s*display:\s*none/.test(printBlock));
ok('print: .no-print UI (topbar, bottom nav, overlay) is display:none',
  /\.no-print[^{]*\{\s*display:\s*none/.test(printBlock));

// ---- 2–3 page resumes are first-class: the sheet grows, nothing clips -------
ok('multi-page: the printed sheet grows past one A4 (min-height, not a fixed height)',
  /\.print-root \.sheet \{[^}]*min-height:\s*297mm/.test(printBlock) &&
  !/\.print-root \.sheet \{[^}]*[^-]height:\s*297mm/.test(printBlock));
ok('multi-page: entries keep together across a page break (break-inside avoid)',
  /\.print-root \.sheet \.s-item[\s\S]*?break-inside:\s*avoid/.test(printBlock));
ok('multi-page: a section heading is never left alone at a page bottom (break-after avoid)',
  /\.print-root \.sheet \.s-sec-title[\s\S]*?break-after:\s*avoid/.test(printBlock));

// ---- professional readability + left-rail rules -----------------------------
ok('layout: base resume ink is dark enough for print',
  /\.sheet\s*\{[^}]*color:\s*#182230/.test(templatesCss));
ok('layout: contact details use a stronger readable weight',
  /\.s-contact\s*\{[^}]*font-weight:\s*600/.test(templatesCss));
ok('layout: employer and issuer metadata are dark and semibold',
  /\.s-company, \.s-issuer\s*\{[^}]*color:\s*#273345[^}]*font-weight:\s*650/.test(templatesCss));
ok('layout: important work bullets use stronger print-safe ink',
  /\.sec-experience \.s-item > ul li,[\s\S]*?\.sec-achievements > ul li\s*\{[^}]*color:\s*#253142[^}]*font-weight:\s*500/.test(templatesCss));
ok('layout: education institution and year are print-readable',
  /\.s-table \.edu-school\s*\{[^}]*color:\s*#273345[^}]*font-weight:\s*600/.test(templatesCss) &&
  /\.s-table \.edu-year\s*\{[^}]*color:\s*#465264[^}]*font-weight:\s*550/.test(templatesCss));
ok('layout: experience company and cert issuer get semantic emphasis classes',
  (previewSrc.match(/s-item-sub s-company/g) || []).length === 2 &&
  previewSrc.includes('s-item-sub s-issuer'));
ok('layout: display-family header contacts are also strongly readable',
  /\.tpl-masthead \.mast-strip,[\s\S]*?\.tpl-tintsheet \.tint-contact\s*\{[^}]*font-weight:\s*600[^}]*color:\s*#303b4a/.test(templatesCss));
ok('layout: dates wrap instead of ellipsizing/clipping',
  /\.s-dates\s*\{[^}]*white-space:\s*normal[^}]*overflow:\s*visible[^}]*text-overflow:\s*clip/.test(templatesCss));
ok('layout: infographic facts rail is on the left',
  /\.tpl-infographic\s*\{\s*flex-direction:\s*row-reverse/.test(templatesCss));
ok('layout: banner facts rail is on the left',
  /\.tpl-banner \.rails\s*\{[^}]*flex-direction:\s*row-reverse/.test(templatesCss));
ok('layout: masthead facts rail is on the left',
  /\.tpl-masthead \.mast-cols\s*\{[^}]*flex-direction:\s*row-reverse/.test(templatesCss));
ok('layout: tint-sheet facts rail is on the left',
  /\.tpl-tintsheet \.tint-cols\s*\{[^}]*flex-direction:\s*row-reverse/.test(templatesCss));

// ---- the editor's print root contains ONLY the sheet ------------------------
const editor = readFileSync(join(root, 'src', 'components', 'Editor.tsx'), 'utf8');
const pdfApi = readFileSync(join(root, 'api', 'pdf.ts'), 'utf8');
const m = editor.match(/<div className="print-root"[\s\S]*?>([\s\S]*?)<\/div>/);
ok('editor: print-root exists', !!m);
ok('editor: print-root holds exactly <Preview r={r} /> — nothing else prints',
  !!m && /^\s*<Preview r=\{r\} \/>?\s*$/.test(m[1]));
ok('multi-page: the editor shows a live page count (A4 · N pages) badge',
  editor.includes('page-badge') && /onPages=\{setPages\}/.test(editor));

ok('download: direct PDF uses the browser download flow',
  editor.includes("fetch('/api/pdf'") && editor.includes('link.download = filename'));
ok('download: browser print remains a resilient fallback',
  editor.includes('window.print()') && editor.includes('download_fallback'));
ok('download: PDF renderer prints backgrounds and honours A4 CSS',
  /printBackground:\s*true/.test(pdfApi) && /preferCSSPageSize:\s*true/.test(pdfApi));
ok('security: PDF renderer blocks outbound server-side requests',
  pdfApi.includes('setRequestInterception(true)') && pdfApi.includes('req.abort()'));
ok('download: Vercel PDF function uses the supported default fetch handler',
  pdfApi.includes('export default {') && pdfApi.includes('async fetch(request: Request)'));
ok('download: PDF function only accepts POST',
  pdfApi.includes("request.method !== 'POST'") && pdfApi.includes("Allow: 'POST'"));

// ---- the flagship sample itself is watermark-free content -------------------
const sampleJson = JSON.stringify(sampleR).toLowerCase();
ok('sample resume (Amit Shukla) carries no app URLs or branding',
  !BRAND.some((b) => sampleJson.includes(b)));
ok('sample resume has the expected identity',
  sampleR.personal.fullName === 'Amit Shukla' && sampleR.personal.headline === 'Senior Software Engineer');

process.exit(checks(out) ? 0 : 1);
